"""Independent source, native-path and strict equipment projection checks."""
import copy
import hashlib
import json
import os
from pathlib import Path
import struct
import unittest

from tools import client72_d02_equipment_resource as card


class EquipmentResourceContract(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        path = Path(os.environ.get('CLIENT72_D02_EQUIPMENT_REPORT', str(card.RAW / 'final-first.json')))
        cls.report = json.loads(path.read_bytes())
        if cls.report['sourceSHA256'] != card.sha(Path(card.__file__).read_bytes()):
            raise ValueError('Report was not generated by the current frozen tool')
        cls.tables = cls.report['tables']
        cls.enums = {x['typeIndex']: x for x in [cls.report['enumAlignment']['curveTypes'], cls.report['enumAlignment']['curveArithmetic']]}
        original = json.loads(card.OLD_REPORT.read_bytes())
        cls.enums.update({x['typeIndex']: x for x in original['tables'][0]['enumSymbols']})
        cls.sources = {name: (card.RAW / 'java-epoch0' / name).read_text('utf8')
                       for name in json.loads((card.RAW / 'java-manifest.private.json').read_bytes())}

    def test_exact_three_tables_and_contiguous_source_spans(self):
        expected = {'Avatar': (169, 64384), 'Weapon': (288, 128936), 'WeaponCurve': (100, 26204)}
        for table in self.tables:
            self.assertEqual((table['count'], table['payloadBytes']), expected[table['name']])
            self.assertEqual(table['cursor'], table['payloadBytes'])
            self.assertLess(table['trace']['instructions'], 2_000_000)
            spans = sorted((row['source'] for row in table['rows']), key=lambda x: x['begin'])
            self.assertEqual(spans[0]['begin'], 4)
            self.assertEqual(spans[-1]['end'], table['payloadBytes'])
            self.assertTrue(all(a['end'] == b['begin'] for a, b in zip(spans, spans[1:])))

    def test_independent_payload_and_row_hashes(self):
        for table in self.tables:
            file = card.CURVE if table['name'] == 'WeaponCurve' else card.SOURCE / (table['name'] + '.native-m_bytes.bin')
            data = file.read_bytes()
            self.assertEqual(hashlib.sha256(data).hexdigest(), table['payloadSHA256'])
            for row in table['rows']:
                source = row['source']
                self.assertEqual(hashlib.sha256(data[source['begin']:source['end']]).hexdigest(), source['sha256'])

    def test_initial_weapon_actual_lookup_and_independent_nonzero(self):
        cases = self.report['consumers']['initialWeapon']
        self.assertEqual([(x['avatarId'], x['initialWeapon']) for x in cases], [(10000005, 11101), (10000007, 11101), (10000136, 14101)])
        for row in cases:
            self.assertEqual(row['lookup']['stop'], '0x14e9b1684')
            self.assertGreater(row['lookup']['executedAddresses'].get('0x1578b66f0', 0), 0)
            self.assertEqual(row['idProducer']['stop'], '0x14e9b17a5')
            self.assertEqual(row['equipCaseProducer']['stop'], '0x14e9b183b')
            self.assertEqual((row['initialLevel'], row['equipCase']), (1, 6))

    def test_uint64_guid_and_resource_hash_are_not_truncated(self):
        for row in self.report['consumers']['initialWeapon']:
            self.assertGreater(int(row['syntheticGuidDecimal']), 1 << 63)
            self.assertEqual(int(row['syntheticGuidBits'], 16), int(row['syntheticGuidDecimal']))
            self.assertTrue(row['guidPreserved'])
        avatar = next(t for t in self.tables if t['name'] == 'Avatar')['selected'][0]
        value = next(f['value'] for f in avatar['fields'] if f['offset'] == '0x28')
        self.assertEqual(int(value['decimal']), int(value['bits'], 16))
        self.assertGreater(int(value['decimal']), 1 << 63)

    def test_native_property_prefix_and_float32_oracle(self):
        rows = self.report['consumers']['weaponProperties']
        self.assertEqual([(x['index'], x['level']) for x in rows], [(0, 1), (1, 1), (0, 20), (1, 20)])
        for row in rows:
            base, factor = (struct.unpack('<f', bytes.fromhex(row[name])[::-1])[0] for name in ('initValueBits', 'curveValueBits'))
            expected = struct.unpack('<I', struct.pack('<f', base * factor))[0]
            self.assertEqual(int(row['nativeValueBeforePromoteBits'], 16), expected)
            self.assertEqual(row['trace']['stop'], '0x1507585f0')
            self.assertGreater(row['trace']['executedAddresses'].get('0x150757a00', 0), 0)
            self.assertEqual(row['arith'], 2)

    def test_promote_source_id_stops_before_unprovided_table(self):
        for row in self.report['consumers']['weaponProperties']:
            self.assertEqual(row['weaponPromoteId'], 11101)
            self.assertEqual(row['promoteLevel'], 0)
            self.assertEqual(row['promoteIdConsumer']['stop'], '0x147bf60c0')
            self.assertFalse(row['actualPromoteRowSupplied'])

    def test_original_two_properties_none_and_zero_retained(self):
        weapon = next(x for x in self.report['javaProjectionFragments'] if x['table'] == 'Weapon')['javaFields']
        self.assertEqual(weapon['itemType'], 'ITEM_WEAPON')
        self.assertEqual(weapon['weaponPromoteId'], 11101)
        properties = weapon['weaponProp']
        self.assertEqual(len(properties), 2)
        self.assertEqual([x['propType'] for x in properties], ['FIGHT_PROP_BASE_ATTACK', 'FIGHT_PROP_NONE'])
        self.assertEqual([x['type'] for x in properties], ['GROW_CURVE_ATTACK_101', 'GROW_CURVE_CRITICAL_101'])
        self.assertEqual(struct.pack('<f', properties[0]['initValue']).hex(), 'c3f5b941')
        self.assertEqual(struct.pack('<f', properties[1]['initValue']).hex(), '00000000')

    def test_all_required_curve_references_are_exact_multi(self):
        curves = [x for x in self.report['javaProjectionFragments'] if x['table'] == 'WeaponCurve']
        self.assertEqual([x['key'] for x in curves], list(range(1, 101)))
        required = {'GROW_CURVE_ATTACK_101', 'GROW_CURVE_CRITICAL_101'}
        for row in curves:
            selected = [x for x in row['javaFields']['curveInfos'] if x['type'] in required]
            self.assertEqual(len(selected), 2)
            self.assertTrue(all(x['arith'] == 'ARITH_MULTI' for x in selected))

    def test_actual_missing_weapon_query_is_null(self):
        row = self.report['consumers']['missingWeapon']
        self.assertTrue(row['returnedNull'])
        self.assertEqual(row['trace']['stop'], hex(card.RETURN))

    def test_missing_positive_item_reference_rejected(self):
        changed = copy.deepcopy(self.tables)
        weapon = next(x for x in changed if x['name'] == 'Weapon')
        weapon['rows'] = [x for x in weapon['rows'] if x['key'] != 11101]
        with self.assertRaisesRegex(ValueError, 'initialWeapon'):
            card.project(changed, self.enums, self.sources)

    def test_missing_required_curve_and_duplicate_type_rejected(self):
        for duplicate in (False, True):
            changed = copy.deepcopy(self.tables)
            first = next(x for x in changed if x['name'] == 'WeaponCurve')['rows'][0]
            values = next(x['value'] for x in first['fields'] if x['offset'] == '0x10')
            target = next(x for x in values if next(y['value']['value'] for y in x if y['offset'] == '0x0') == 1101)
            values.append(copy.deepcopy(target)) if duplicate else values.remove(target)
            with self.assertRaises(ValueError):
                card.project(changed, self.enums, self.sources)

    def test_unknown_named_enums_and_no_none_fallback(self):
        for domain in (34819, 32419, 54063, 58570):
            with self.assertRaises(ValueError):
                card.exact_enum(0x7fffffff, domain, self.enums)
        with self.assertRaises(ValueError):
            card.exact_enum(4, 34819, self.enums, {'ITEM_WEAPON': 3})

    def test_known_nonmultiply_required_curve_rejected(self):
        changed = copy.deepcopy(self.tables)
        first = next(x for x in changed if x['name'] == 'WeaponCurve')['rows'][0]
        infos = next(x['value'] for x in first['fields'] if x['offset'] == '0x10')
        target = next(x for x in infos if next(y['value']['value'] for y in x if y['offset'] == '0x0') == 1101)
        next(x['value'] for x in target if x['offset'] == '0x4')['value'] = 1
        with self.assertRaisesRegex(ValueError, 'multiplier'):
            card.project(changed, self.enums, self.sources)

    def test_absent_property_field_does_not_become_observed_zero(self):
        changed = copy.deepcopy(self.tables)
        selected = next(x for x in changed if x['name'] == 'Weapon')['selected'][0]
        backing = next(x['value'] for x in selected['fields'] if x['offset'] == '0x20')
        props = next(x['value'] for x in backing if x['offset'] == '0x68')
        props[1] = [x for x in props[1] if x['offset'] != '0x14']
        with self.assertRaises(KeyError):
            card.project(changed, self.enums, self.sources)

    def test_java_positive_int_boundary_rejected_without_truncation(self):
        for value in (0, -1, 0x80000000, 0xffffffff, 1.0, True):
            with self.assertRaises(ValueError):
                card.java_id(value)
        self.assertEqual(card.java_id(0x7fffffff), 0x7fffffff)

    def test_scope_and_frozen_sources(self):
        self.assertEqual(len(self.report['staticConsumers']), 10)
        self.assertTrue(all(x['fragmentOnly'] for x in self.report['javaProjectionFragments']))
        self.assertFalse(self.report['activeRevisionVerified'])
        self.assertIsNone(self.report['activeSelectedRevision'])
        for name in ('javaResourcesLoaded', 'resourceReady', 'd02Complete', 'completeAvatarHandler', 'wholeEquipmentAssignment'):
            self.assertFalse(self.report[name])
        self.assertTrue(self.report['fiveInputsRecheckedAfterNative'])
        for name, expected in self.report['sourcePins'].items():
            if not name.startswith('GAME_PATH/'):
                self.assertEqual(card.sha((card.ROOT / name).read_bytes()), expected)


if __name__ == '__main__':
    unittest.main()
