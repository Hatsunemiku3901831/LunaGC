"""Generate the fixed CN72 login wire closure; raw names do not assert semantics."""
import argparse
import json
from pathlib import Path
import re

try:
    from .extract_client72 import HASHES, read_verified
    from .generate_born72_sources import OPCODES, PROTO, write_sources
    from .validate_protocol72 import validate
except ImportError:
    from extract_client72 import HASHES, read_verified
    from generate_born72_sources import OPCODES, PROTO, write_sources
    from validate_protocol72 import validate

ROOTS = {'GetPlayerTokenRsp': 'CLDBKDNJHFG', 'PlayerLoginReq': 'KOHBOMDDFCB',
         'PlayerLoginRsp': 'NDENMDAIAMC'}
COMMANDS = {'GetPlayerTokenRsp': 27808, 'PlayerLoginReq': 23172, 'PlayerLoginRsp': 20835}
SEMANTICS = {
    'GetPlayerTokenRsp': {6: 'token', 9: 'uid', 14: 'retcode', 208: 'sign', 477: 'server_rand_key'},
    'PlayerLoginReq': {1: 'token', 2: 'system_version', 4: 'language_type', 7: 'device_name',
        9: 'client_version', 10: 'platform_type', 12: 'channel_id', 15: 'device_info',
        213: 'fp_id', 274: 'client_data_version', 345: 'cps', 364: 'sub_channel_id',
        552: 'robot_check_output', 891: 'game_version', 1533: 'uapc', 1785: 'client_ip_str',
        1931: 'network_ip', 1996: 'client_version_hash'},
    'PlayerLoginRsp': {8: 'retcode', 437: 'client_md5', 744: 'client_silence_version_suffix',
        1255: 'client_silence_md5', 1792: 'client_version_suffix'},
}
OBSERVATIONS = ('login-wire-observations.json', 'response-wire-observations.json',
                'response-leaf-wire-observations.json', 'response-graph-observations.json')


def field_shape(field):
    return tuple(field.get(k) for k in ('clientField', 'tag', 'type', 'cardinality',
        'presence', 'packed', 'nestedType', 'oneof', 'keyType', 'valueType'))


def render_message(message, name, semantics, *, preserve_scalar_presence=False):
    fields = []
    oneofs = {}
    for field in sorted(message['fields'], key=lambda f: f['tag']):
        kind = field['type']
        if kind == 'map':
            value = field['nestedType'] if field['valueType'] == 'message' else field['valueType']
            kind = f"map<{field['keyType']}, {value}>"
        elif kind == 'message':
            kind = field['nestedType']
        prefix = 'repeated ' if field['cardinality'] == 'repeated' else (
            'optional ' if preserve_scalar_presence and field['type'] not in ('map', 'message') and not field.get('oneof') else '')
        identifier = semantics.get(field['tag'], field['clientField'])
        if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', identifier):
            raise ValueError('Invalid observed field identifier')
        option = ' [packed = true]' if field['packed'] else ''
        line = f"{prefix}{kind} {identifier} = {field['tag']}{option};"
        if field.get('oneof'):
            oneofs.setdefault(field['oneof'], []).append(line)
        else:
            fields.append('  ' + line)
    for group, lines in oneofs.items():
        fields.extend(['  oneof ' + group + ' {', *('    ' + s for s in lines), '  }'])
    return 'message ' + name + ' {\n' + '\n'.join(fields) + '\n}\n'


def render_sources(mapping, profile, reports, opcode_source):
    errors = validate(mapping, profile)
    if len(reports) != 4 or any(r.get('inputSHA256') != HASHES for r in reports):
        raise ValueError('Fixed login observations required')
    messages = {}
    for report in reports[:3]:
        for message in report['messages']:
            name = message['clientType']
            if name in messages and [field_shape(f) for f in message['fields']] != [
                    field_shape(f) for f in messages[name]['fields']]:
                errors.append('Inconsistent shared wire type: ' + name)
            messages[name] = message
    if len(messages) != 21 or sum(len(m['fields']) for m in messages.values()) != 198:
        errors.append('Reviewed login wire closure changed')
    graph = reports[3]
    if graph.get('schemaMessages') != 18 or graph.get('fields') != 137 or len(graph.get('contentBindings', [])) != 21:
        errors.append('Nonempty response graph evidence missing')
    known = set(messages)
    for message in messages.values():
        for field in message['fields']:
            if field.get('nestedType') and field['nestedType'] not in known:
                errors.append('Missing observed nested dependency: ' + field['nestedType'])
    tables = {key: {r['semanticName']: r for r in mapping[key]} for key in ('opcodes', 'messages', 'schemas')}
    outputs = {}
    preamble = ('// Generated by tools/generate_login72_contract.py from fixed CN 7.2 evidence.\n'
                '// Unverified business meanings retain raw names; enums retain int32 storage.\n'
                '// Wire integration only, not a complete login or client acceptance.\n'
                'syntax = "proto3";\n\noption java_package = "emu.grasscutter.net.proto";\n')
    for name, raw in ROOTS.items():
        op, identity, schema = (tables[key][name] for key in tables)
        if any(r['status'] != 'verified' for r in (op, identity)) or identity.get('clientType') != raw or op.get('cmdId') != COMMANDS[name]:
            errors.append(name + ': reviewed identity/CmdID changed')
        actual_semantics = {f['tag']: f['semanticField'] for f in schema['fields'] if f['status'] == 'verified'}
        if actual_semantics != SEMANTICS[name]:
            errors.append(name + ': reviewed semantic boundary changed')
        observed = messages[raw]
        keys = ('clientField', 'tag', 'type', 'cardinality', 'presence', 'packed')
        shape = lambda f: tuple(f.get(k) for k in keys)
        if [shape(f) for f in schema['fields']] != [shape(f) for f in observed['fields']]:
            errors.append(name + ': mapping differs from independent wire evidence')
        outputs[PROTO / (name + '.proto')] = preamble + f'option java_outer_classname = "{name}OuterClass";\n\nimport "Client72LoginNested.proto";\n\n' + render_message(observed, name, SEMANTICS[name])
    nested = [m for n, m in sorted(messages.items()) if n not in ROOTS.values()]
    outputs[PROTO / 'Client72LoginNested.proto'] = preamble + (
        '// Optional primitive fields are a Java merge adapter for observed explicit-zero/empty overwrites.\n'
        '// They do not assert optional declarations in the original target Proto.\n'
        'option java_outer_classname = "Client72LoginNestedOuterClass";\n\n') + '\n'.join(
            render_message(m, m['clientType'], {}, preserve_scalar_presence=True) for m in nested)
    for name, value in re.findall(r'public static final int (\w+) = (-?\d+);', opcode_source):
        if name not in COMMANDS and int(value) in COMMANDS.values():
            errors.append(name + ': unreviewed command collision')
    for name, value in COMMANDS.items():
        opcode_source, count = re.subn(rf'public static final int {name} = -?\d+;', f'public static final int {name} = {value};', opcode_source)
        if count != 1:
            errors.append(name + ': expected one canonical opcode')
    outputs[OPCODES] = opcode_source
    if errors:
        raise ValueError('\n'.join(errors))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for name, digest in HASHES.items():
        read_verified(args.client / name, digest)
    directory = root / 'protocol/cn-7.2'
    load = lambda name: json.loads((directory / name).read_text('utf8'))
    outputs = render_sources(load('mappings.json'), load('profile.json'), [load(n) for n in OBSERVATIONS], (root / OPCODES).read_text('utf8'))
    drift = write_sources(root, outputs, check=args.check)
    print(json.dumps(dict(scope='F-02b1 21 types / 198 wire fields', check=args.check, drift=drift), indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__ == '__main__':
    main()
