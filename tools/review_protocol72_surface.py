"""Check a manually reviewed source snapshot; never approve target protocol IDs.

Review records are deliberately not regenerated by this command. Source drift,
new dynamic sites, or changed numeric dispatch candidates require human review.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

try:
    from .inventory_protocol import JAVA, clean_source, inventory, line_at
except ImportError:
    from inventory_protocol import JAVA, clean_source, inventory, line_at


CLASSIFICATIONS = {
    'private-constant-chain', 'constant-alias', 'external-config',
    'external-api', 'post-event-copy',
}
SITE_KEYS = ('file', 'line', 'kind', 'expression')
NUMERIC_CASE = re.compile(r'\bcase\s+(-?(?:0[xX][0-9a-fA-F]+|[0-9]+)\b[^:\n]*?)(?=:|->)')


def source_path(repo, relative):
    path = Path(relative)
    if path.is_absolute() or '..' in path.parts or '\\' in relative:
        raise ValueError('review paths must be relative POSIX paths')
    resolved = (repo / path).resolve()
    if not resolved.is_relative_to(repo.resolve()):
        raise ValueError('review path escapes repository')
    return resolved


def text_hash(path):
    # Same UTF-8/universal-newline fingerprint used by inventory_protocol.
    return hashlib.sha256(path.read_text('utf-8').encode('utf-8')).hexdigest()


def numeric_cases(repo):
    rows = []
    for part in ('server', 'net'):
        for path in sorted((repo / JAVA / part).rglob('*.java')):
            clean = clean_source(path.read_text('utf-8'), True)
            for match in NUMERIC_CASE.finditer(clean):
                rows.append(dict(file=path.relative_to(repo).as_posix(),
                                 line=line_at(clean, match.start()),
                                 expression=match[1].strip()))
    return sorted(rows, key=lambda row: (row['file'], row['line']))


def check_review(repo, review, current=None):
    current = inventory(repo) if current is None else current
    errors = []
    if review.get('schemaVersion') != 1 or review.get('scope') != 'server-source-baseline':
        errors.append('unsupported review format/scope')
    sources = review.get('sourceSHA256', {})
    for name, digest in sorted(sources.items()):
        try:
            path = source_path(repo, name)
            if not path.is_file() or text_hash(path) != digest:
                errors.append(f'reviewed source changed: {name}')
        except ValueError as exc:
            errors.append(f'{name}: {exc}')
    groups = review.get('groups', {})
    reviewed = review.get('dynamicSites', [])
    actual = [row for row in current['sends'] if row['value'] is None]
    site_key = lambda row: tuple(row.get(key) for key in SITE_KEYS)
    keys = [site_key(row) for row in reviewed]
    if len(keys) != len(set(keys)):
        errors.append('duplicate reviewed dynamic site')
    if Counter(keys) != Counter(site_key(row) for row in actual):
        errors.append('dynamic send surface changed; review additions/removals/expressions')
    used_groups = {row.get('group') for row in reviewed}
    if used_groups != set(groups):
        errors.append('dynamic review has missing or unused groups')
    for row in reviewed:
        if row.get('file') not in sources:
            errors.append(f'dynamic site lacks source fingerprint: {row.get("file")}')
    values = {row['name']: row['value'] for row in current['constants']}
    opcode_file = f'{JAVA}/net/packet/PacketOpcodes.java'
    for name, group in groups.items():
        if group.get('classification') not in CLASSIFICATIONS or not group.get('finding'):
            errors.append(f'incomplete review group: {name}')
        if not group.get('sources') or any(p not in sources for p in group.get('sources', [])):
            errors.append(f'group lacks reviewed source fingerprints: {name}')
        for constant, value in group.get('legacyConstants', {}).items():
            if opcode_file not in sources or constant not in values or values[constant] != value:
                errors.append(f'legacy constant binding changed: {name}/{constant}')
    cases = numeric_cases(repo)
    if cases != review.get('numericCases'):
        errors.append('numeric switch surface changed in server/net')
    domains = review.get('numericDomains', {})
    if set(domains) != {row['file'] for row in cases}:
        errors.append('numeric case domain review is incomplete')
    if any(p not in sources or not domain for p, domain in domains.items()):
        errors.append('numeric case domain lacks source fingerprint/finding')
    numeric_sends = [row for row in current['sends']
                     if re.fullmatch(r'-?(?:0[xX][0-9a-fA-F]+|[0-9]+)', row['expression'])]
    if numeric_sends != review.get('numericSends'):
        errors.append('numeric send arguments changed')
    if current['configurationCandidates'] != review.get('configurationCandidates'):
        errors.append('configuration candidate surface changed')
    for row in current['configurationCandidates']:
        if row['file'] not in sources:
            errors.append(f'configuration lacks source fingerprint: {row["file"]}')
    boundaries = review.get('openBoundaries', [])
    if not boundaries:
        errors.append('external/runtime review boundaries must remain explicit')
    for boundary in boundaries:
        if not boundary.get('finding') or not boundary.get('nextTask') or not boundary.get('sources'):
            errors.append('incomplete external/runtime boundary')
        if any(p not in sources for p in boundary.get('sources', [])):
            errors.append('boundary lacks source fingerprint')
    return dict(scope='Source review only; no target identity, CmdID or wire approval',
                reviewMatchesSource=not errors, protocolReady=False,
                counts=dict(dynamicSites=len(actual), groups=len(groups),
                            reviewedSources=len(sources), numericCases=len(cases),
                            numericSends=len(numeric_sends), openBoundaries=len(boundaries)),
                classifications=dict(sorted(Counter(g['classification'] for g in groups.values()).items())),
                errors=errors)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--review', type=Path, default=Path('protocol/cn-7.2/server-surface-review.json'))
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    review = json.loads(args.review.read_text('utf-8'))
    report = check_review(args.repo, review)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', 'utf-8')
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if report['reviewMatchesSource'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
