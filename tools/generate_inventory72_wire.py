"""Generate a separate full raw inventory wire adapter, without approving its semantics."""
import argparse
import hashlib
import json
from pathlib import Path

try:
    from .extract_client72 import HASHES, read_verified
    from .generate_born72_sources import PROTO, write_sources
except ImportError:
    from extract_client72 import HASHES, read_verified
    from generate_born72_sources import PROTO, write_sources

# Canonical JSON LF fingerprint of the approved complete native graph report.
RAW_CANONICAL_SHA256 = 'b21904536dc21997f2ee9c1ecb2761e63d521f8cebb72a7320620ec7b3660fe8'
OUTPUT = PROTO / 'Client72InventoryWire.proto'


def render_sources(raw):
    digest = hashlib.sha256((json.dumps(raw, indent=2) + '\n').encode('utf8')).hexdigest()
    if digest != RAW_CANONICAL_SHA256 or raw.get('inputSHA256') != HASHES:
        raise ValueError('Approved full inventory raw evidence changed')
    names = {row['typeIndex']: row['clientType'] for row in raw['messages']}
    messages = []
    for row in raw['messages']:
        lines, groups = [], {}
        for field in sorted(row['fields'], key=lambda f: f['tag']):
            kind = field['type']
            if kind == 'message': kind = names[field['nestedTypeIndex']]
            if kind == 'map':
                kind = f"map<{field['keyType']}, {field['valueType']}>"
            prefix = 'repeated ' if field['cardinality'] == 'repeated' else (
                'optional ' if field['type'] not in ('message', 'map') and not field.get('oneof') else '')
            line = f"  {prefix}{kind} {field['clientField']} = {field['tag']};"
            if field.get('oneof'): groups.setdefault(field['oneof'], []).append(line)
            else: lines.append(line)
        for name, branches in groups.items():
            lines += ['  oneof ' + name + ' {'] + ['  ' + branch for branch in branches] + ['  }']
        messages.append('message ' + row['clientType'] + ' {\n' + '\n'.join(lines) + '\n}\n')
    return {OUTPUT: (
        '// Generated by tools/generate_inventory72_wire.py from fixed native raw evidence.\n'
        '// All names remain raw; this adapter does not migrate the legacy sender or approve business meanings.\n'
        '// Optional scalar presence preserves native same-branch explicit-zero merge; not original Proto syntax.\n'
        'syntax = "proto3";\n\npackage cn72.inventorywire;\n'
        'option java_package = "emu.grasscutter.net.proto";\n'
        'option java_outer_classname = "Client72InventoryWireOuterClass";\n\n' + '\n'.join(messages))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); root = Path(__file__).resolve().parents[1]
    for name, digest in HASHES.items(): read_verified(args.client / name, digest)
    raw = json.loads((root / 'protocol/cn-7.2/inventory-graph-observations.json').read_text('utf8'))
    drift = write_sources(root, render_sources(raw), check=args.check)
    print(json.dumps(dict(scope='F-03d2c1 standalone 15-type/47-field raw wire only', check=args.check, drift=drift), indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__ == '__main__': main()
