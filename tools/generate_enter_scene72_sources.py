"""Generate the verified minimal entry notification and its complete raw wire family."""
import argparse
import json
from pathlib import Path
import re

try:
    from .extract_client72 import HASHES, read_verified
    from .generate_born72_sources import OPCODES, PROTO, write_sources
    from .client72_enter_scene_contract import validate_summary
except ImportError:
    from extract_client72 import HASHES, read_verified
    from generate_born72_sources import OPCODES, PROTO, write_sources
    from client72_enter_scene_contract import validate_summary

FIELDS={7:'scene_id',8:'type',10:'enter_scene_token',14:'pos'}


def render_message(row,name,names,semantics):
    lines=[]
    for f in sorted(row['fields'],key=lambda f:f['tag']):
        kind=names[f['nestedTypeIndex']] if f['type']=='message' else f['type']
        repeated=f['cardinality']=='repeated'
        label='repeated ' if repeated else 'optional ' if f['type']!='message' else ''
        options=' [packed = true]' if repeated and f.get('packed') else ''
        lines.append(f"  {label}{kind} {semantics.get(f['tag'],f['clientField'])} = {f['tag']}{options};")
    return 'message '+name+' {\n'+'\n'.join(lines)+'\n}\n'


def render_sources(contract,handshake,opcode_source):
    validate_summary(contract)
    if contract['inputSHA256']!=HASHES or handshake['inputSHA256']!=HASHES:
        raise ValueError('Fixed target input required')
    bindings={b['tag']:b for b in contract['semanticBindings'] if b['typeIndex']==46311}
    if {tag:b['name'] for tag,b in bindings.items()}!=FIELDS or any(b['status']!='verified-offline' for b in bindings.values()):
        raise ValueError('Four independently named minimum sender fields required')
    rows={r['typeIndex']:r for r in contract['rawSchemas']}
    if len(rows)!=8 or sum(len(r['fields']) for r in rows.values())!=44:
        raise ValueError('Complete reviewed raw entry family required')
    shared=next(r for r in handshake['messages'] if r['typeIndex']==84343)
    shape=lambda r:sorted((f['tag'],f['clientField'],f['objectOffset'],f['type']) for f in r['fields'])
    if shape(rows[84343])!=shape(shared):raise ValueError('Shared native Vector wire differs')
    names={index:('PlayerEnterSceneNotify' if index==46311 else r['clientType']) for index,r in rows.items()}
    preamble=('// Generated by tools/generate_enter_scene72_sources.py from fixed native evidence.\n'
        '// Only four sender fields are named; other meanings remain unknown and are omitted.\n'
        '// Optional is a Java presence/zero-merge adapter, not recovered target Proto syntax.\n'
        'syntax = "proto3";\noption java_package = "emu.grasscutter.net.proto";\n')
    root=(preamble+'option java_outer_classname = "PlayerEnterSceneNotifyOuterClass";\n\n'
        'import "Client72SceneHandshakeNested.proto";\nimport "Client72EnterSceneNested.proto";\n\n'
        +render_message(rows[46311],'PlayerEnterSceneNotify',names,FIELDS))
    nested=(preamble+'option java_outer_classname = "Client72EnterSceneNestedOuterClass";\n\n'
        +'\n'.join(render_message(row,names[index],names,{}) for index,row in rows.items() if index not in {46311,84343}))
    declarations=re.findall(r'public static final int (\w+) = (-?\d+);',opcode_source)
    if any(int(value)==27748 and name!='PlayerEnterSceneNotify' for name,value in declarations):
        raise ValueError('Unreviewed target entry command collision')
    values=[int(value) for name,value in declarations if name=='PlayerEnterSceneNotify']
    if len(values)!=1 or values[0] not in {9582,27748}:raise ValueError('Unexpected entry command state')
    opcode_source=re.sub(r'public static final int PlayerEnterSceneNotify = -?\d+;',
        'public static final int PlayerEnterSceneNotify = 27748;',opcode_source)
    return {PROTO/'PlayerEnterSceneNotify.proto':root,PROTO/'Client72EnterSceneNested.proto':nested,OPCODES:opcode_source}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--client',type=Path,required=True);p.add_argument('--check',action='store_true')
    a=p.parse_args();root=Path(__file__).resolve().parents[1]
    for name,digest in HASHES.items():read_verified(a.client/name,digest)
    load=lambda name:json.loads((root/'protocol/cn-7.2'/name).read_text('utf8'))
    outputs=render_sources(load('enter-scene-contract-observations.json'),load('scene-handshake-observations.json'),(root/OPCODES).read_text('utf8'))
    drift=write_sources(root,outputs,check=a.check)
    print(json.dumps(dict(scope='F-03 four-field minimum sender / 8 raw types 44 fields',check=a.check,drift=drift),indent=2))
    raise SystemExit(bool(drift) if a.check else 0)


if __name__=='__main__':main()
