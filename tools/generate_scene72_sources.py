RETIRED = {'DIICIBFPICB': (21392, -121392), '_MonsterChessV2BattleDataNotify': (1017, -101017),
           'MonsterChessV2BattleDataNotify': (1017, -201017), 'AvatarSelectionDataNotify': (21136, -121136)}
CAPACITY = {1:'reliquary_count_limit',5:'furniture_count_limit',6:'store_type',
            9:'weapon_count_limit',14:'material_count_limit'}
DEFAULTS = {(17278,0xC18A,0x9435),(36349,0xFFFF7F50,0xFFFF2E48),
            (74698,0x3966,0xFFFFAE74),(51326,0x12F00,0xFFFF8333)}


def render_message(row, name, names, semantics=None, *, optional=True):
    lines=[]
    for field in sorted(row['fields'],key=lambda f:f['tag']):
        kind=field['type']
        if kind=='message':kind=names[field['nestedTypeIndex']]
        elif kind=='enum':kind='int32'
        prefix='optional ' if optional and field['type']!='message' else ''
        identifier=(semantics or {}).get(field['tag'],field['clientField'])
        lines.append(f"  {prefix}{kind} {identifier} = {field['tag']};")
    return 'message '+name+' {\n'+'\n'.join(lines)+'\n}\n'


def render_sources(handshake, capacity, raw_capacity, opcode_source):
    validate_summary(handshake)
    defaults={(r['typeIndex'],r['token']['absentRawDefault'],r['retcode']['absentRawDefault'])
              for r in handshake['responsePresenceContract']}
    if defaults!=DEFAULTS:
        raise ValueError('Native constructor presence defaults changed')
    if any(r.get('inputSHA256')!=HASHES for r in (capacity,raw_capacity)):
        raise ValueError('Fixed initialization target required')
    bindings={f['tag']:f['semanticField'] for f in capacity['bindings']}
    if bindings!=CAPACITY or capacity['semanticIdentityStatus']!='verified-offline-purpose-alias' or capacity['cmdId']!=22609:
        raise ValueError('Reviewed inventory capacity contract changed')
    legacy=raw_capacity['legacySelectionAudit']
    if legacy['targetCmd21136Matches'] or legacy['targetTypeAt46070']['name']!='DDFOJHINPLA':
        raise ValueError('Review historical selection notification against changed target')
    roles={r['typeIndex']:r for r in handshake['roles']}
    if len([b for b in handshake['semanticBindings'] if b['typeIndex'] in roles])!=12:
        raise ValueError('Eight token and four retcode application bindings required')
    names={m['typeIndex']:roles[m['typeIndex']]['semanticName'] if m['typeIndex'] in roles else m['clientType'] for m in handshake['messages']}
    outputs={}
    preamble=('// Generated by tools/generate_scene72_sources.py from fixed CN72 native evidence.\n'
        '// Optional scalars are Java wire adapters: retain absent/raw-zero and nested zero merge.\n'
        '// This does not claim optional syntax in the original target Proto or live acceptance.\n'
        'syntax = "proto3";\n\noption java_package = "emu.grasscutter.net.proto";\n')
    nested=[]
    for row in handshake['messages']:
        name=names[row['typeIndex']]
        if row['typeIndex'] not in roles:
            nested.append(render_message(row,name,names));continue
        imports='import "Client72SceneHandshakeNested.proto";\n' if any(f['type']=='message' for f in row['fields']) else ''
        outputs[PROTO/(name+'.proto')]=preamble+f'option java_outer_classname = "{name}OuterClass";\n\n'+imports+'\n'+render_message(row,name,names)
    outputs[PROTO/'Client72SceneHandshakeNested.proto']=preamble+'option java_outer_classname = "Client72SceneHandshakeNestedOuterClass";\n\n'+'\n'.join(nested)
    outputs[PROTO/'StoreWeightLimitNotify.proto']=(
        '// Generated from fixed CN72 inventory capacity consumers; server purpose alias.\n'
        '// Three unconsumed fields retain raw names; enum uses its verified int32 storage.\n'
        'syntax = "proto3";\noption java_package = "emu.grasscutter.net.proto";\n'
        'option java_outer_classname = "StoreWeightLimitNotifyOuterClass";\n\n'+
        render_message(raw_capacity,'StoreWeightLimitNotify',{},CAPACITY,optional=False))
    commands={r['semanticName']:r['cmdId'] for r in roles.values()} | {'StoreWeightLimitNotify':22609}
    for name,(old,inactive) in RETIRED.items():
        match=re.search(rf'public static final int {name} = (-?\d+);',opcode_source)
        if match is None or int(match[1]) not in (old,inactive):
            raise ValueError('Unexpected legacy collision/retirement state: '+name)
        opcode_source=re.sub(rf'public static final int {name} = -?\d+;',f'public static final int {name} = {inactive};',opcode_source)
    for name,value in re.findall(r'public static final int (\w+) = (-?\d+);',opcode_source):
        if name not in commands and int(value) in commands.values():
            raise ValueError('Unreviewed target command collision: '+name)
    for name,value in commands.items():
        opcode_source,count=re.subn(rf'public static final int {name} = -?\d+;',f'public static final int {name} = {value};',opcode_source)
        if count!=1:raise ValueError('Expected one canonical declaration: '+name)
    outputs[OPCODES]=opcode_source
    return outputs


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client',type=Path,required=True)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();root=Path(__file__).resolve().parents[1]
    for n,h in HASHES.items():read_verified(args.client/n,h)
    load=lambda n:json.loads((root/'protocol/cn-7.2'/n).read_text('utf8'))
    outputs=render_sources(load('scene-handshake-observations.json'),load('store-weight-contract-observations.json'),
        load('initialization-wire-observations.json'),(root/OPCODES).read_text('utf8'))
    drift=write_sources(root,outputs,check=args.check)
    print(json.dumps(dict(scope='F-03 eight handshakes / inventory capacity',check=args.check,drift=drift),indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__=='__main__':main()
