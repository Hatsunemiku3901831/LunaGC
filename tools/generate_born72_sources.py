"""Generate only the B-02d verified CN 7.2 born trio; no legacy fallback.

Other protocol messages remain outside this slice. This does not assert P0 readiness.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

try:
    from .extract_client72 import HASHES, read_verified
    from .validate_protocol72 import validate, validate_observations
except ImportError:
    from extract_client72 import HASHES, read_verified
    from validate_protocol72 import validate, validate_observations

NAMES = ('DoSetPlayerBornDataNotify', 'SetPlayerBornDataReq', 'SetPlayerBornDataRsp')
OPCODES = Path('src/main/java/emu/grasscutter/net/packet/PacketOpcodes.java')
PROTO = Path('src/main/proto')


def render_sources(document, profile, commands, born, opcode_source):
    errors = validate(document, profile)
    errors += validate_observations(document, profile, commands,
                                   dict(inputSHA256=born['inputSHA256'], messages=[]),
                                   observations=[('born', born)])
    if born['inputSHA256'] != HASHES:
        errors.append('Born input hashes differ from the fixed target')
    tables = {key: {r['semanticName']: r for r in document[key]}
              for key in ('opcodes', 'messages', 'schemas')}
    roles = {r['semanticName']: r for r in born['roles']}
    observed = {r['semanticName']: r for r in born['messages']}
    outputs = {}
    for name in NAMES:
        opcode, message, schema = (tables[k][name] for k in tables)
        if any(r['status'] != 'verified' for r in (opcode, message, schema)):
            errors.append(f'{name}: all three layers must be verified')
        if message.get('aliases'):
            errors.append(f'{name}: no alias has been verified for this slice')
        if (opcode.get('cmdId') != roles[name]['cmdId'] or
                message.get('clientType') != roles[name]['clientType'] or
                message['direction'] != ('C2S' if name.endswith('Req') else 'S2C')):
            errors.append(f'{name}: native role/direction mismatch')
        if schema['fields'] != [dict(f, evidence=['born-field'], ambiguities=[])
                                for f in observed[name]['fields']]:
            errors.append(f'{name}: schema differs from the fixed born evidence')
        fields = []
        for field in sorted(schema['fields'], key=lambda f: f['tag']):
            if (field['status'] != 'verified' or field['type'] not in {'string', 'uint32', 'int32'} or
                    field['cardinality'] != 'singular' or field['presence'] != 'implicit' or
                    field['packed'] or field.get('nestedType') or field.get('oneof')):
                errors.append(f'{name}: unsupported or unverified field')
            fields.append(f"  {field['type']} {field['semanticField']} = {field['tag']};")
        if not fields and not schema.get('emptySchemaEvidence'):
            errors.append(f'{name}: missing target empty-schema evidence')
        outputs[PROTO / f'{name}.proto'] = (
            '// Generated by tools/generate_born72_sources.py from B-02d verified evidence.\n'
            '// CN 7.2 only; see docs/CLIENT_72_BORN.md. No live acceptance implied.\n'
            'syntax = "proto3";\n\n'
            'option java_package = "emu.grasscutter.net.proto";\n'
            f'option java_outer_classname = "{name}OuterClass";\n\n'
            f'message {name} {{\n' + '\n'.join(fields) + '\n}\n')

    constants = re.findall(r'public static final int (\w+) = (-?\d+);', opcode_source)
    values = {tables['opcodes'][n]['cmdId']: n for n in NAMES}
    for other, value in constants:
        if other not in NAMES and int(value) in values:
            errors.append(f'{other}: collides with verified {values[int(value)]}; not an approved alias')
    for name in NAMES:
        declaration = rf'public static final int {name} = -?\d+;'
        replacement = f"public static final int {name} = {tables['opcodes'][name]['cmdId']};"
        opcode_source, count = re.subn(declaration, replacement, opcode_source)
        if count != 1:
            errors.append(f'{name}: expected exactly one canonical PacketOpcodes declaration')
    outputs[OPCODES] = opcode_source
    if errors:
        raise ValueError('\n'.join(errors))
    return outputs


def write_sources(root, outputs, *, check=False):
    drift = [str(path).replace('\\', '/') for path, content in outputs.items()
             if not (root / path).exists() or (root / path).read_bytes() != content.encode('utf8')]
    if not check:
        for path, content in outputs.items():
            (root / path).write_bytes(content.encode('utf8'))
    return drift


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True, help='Fixed target; hash checked, never launched')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for path, digest in HASHES.items():
        read_verified(args.client / path, digest)
    directory = root / 'protocol/cn-7.2'
    inputs = [json.loads((directory / name).read_text('utf8'))
              for name in ('mappings.json', 'profile.json', 'commands.json', 'born-observations.json')]
    outputs = render_sources(*inputs, (root / OPCODES).read_text('utf8'))
    drift = write_sources(root, outputs, check=args.check)
    print(json.dumps(dict(scope='B-03a born trio only', check=args.check, drift=drift,
                          sha256={str(p).replace('\\', '/'): hashlib.sha256(c.encode()).hexdigest()
                                  for p, c in outputs.items()}), ensure_ascii=False, indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__ == '__main__':
    main()
