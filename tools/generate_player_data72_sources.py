"""Generate the bounded CN72 player-initialization wire adapter; unknowns stay raw."""
import argparse
import json
from pathlib import Path
import re

try:
    from .extract_client72 import HASHES, read_verified
    from .generate_born72_sources import OPCODES, PROTO, write_sources
    from .validate_protocol72 import validate, validate_player_data
except ImportError:
    from extract_client72 import HASHES, read_verified
    from generate_born72_sources import OPCODES, PROTO, write_sources
    from validate_protocol72 import validate, validate_player_data


def render_sources(document, profile, raw, contract, opcode_source):
    errors = validate(document, profile) + validate_player_data(document, profile, raw, contract)
    if errors: raise ValueError('\n'.join(errors))
    schemas = {r['semanticName']: r for r in document['schemas']}
    preamble = ('// Generated by tools/generate_player_data72_sources.py from fixed CN72 native evidence.\n'
        '// Only five field meanings are verified; other fields retain raw names.\n'
        '// Server purpose aliases do not recover original English spelling or prove live acceptance.\n'
        'syntax = "proto3";\n\noption java_package = "emu.grasscutter.net.proto";\n')
    outputs = {}
    for logical, physical, filename in (('PlayerDataNotify', 'PlayerDataNotify', 'PlayerDataNotify'),
                                        ('PropValue', 'Client72PlayerPropValue', 'Client72PlayerDataNested')):
        lines, oneof = [], []
        for field in schemas[logical]['fields']:
            identifier = field['semanticField'] if field['status'] == 'verified' else field['clientField']
            kind = 'map<uint32, Client72PlayerPropValue>' if field['type'] == 'map' else field['type']
            line = f"  {kind} {identifier} = {field['tag']};"
            (oneof if field.get('oneof') else lines).append(line)
        if oneof: lines += ['  oneof raw_value {'] + ['  ' + line for line in oneof] + ['  }']
        imports = 'import "Client72PlayerDataNested.proto";\n\n' if logical == 'PlayerDataNotify' else ''
        outputs[PROTO / (filename + '.proto')] = (preamble +
            f'option java_outer_classname = "{filename}OuterClass";\n\n' + imports +
            f'message {physical} {{\n' + '\n'.join(lines) + '\n}\n')
    for name, value in re.findall(r'public static final int (\w+) = (-?\d+);', opcode_source):
        if name != 'PlayerDataNotify' and int(value) == 7193:
            raise ValueError('Unreviewed target command collision: ' + name)
    opcode_source, count = re.subn(r'public static final int PlayerDataNotify = -?\d+;',
                                   'public static final int PlayerDataNotify = 7193;', opcode_source)
    if count != 1: raise ValueError('Expected one canonical PlayerDataNotify declaration')
    outputs[OPCODES] = opcode_source
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); root = Path(__file__).resolve().parents[1]
    for name, digest in HASHES.items(): read_verified(args.client / name, digest)
    directory = root / 'protocol/cn-7.2'
    values = [json.loads((directory / name).read_text('utf8')) for name in
              ('mappings.json', 'profile.json', 'player-data-wire-observations.json', 'player-data-contract-observations.json')]
    outputs = render_sources(*values, (root / OPCODES).read_text('utf8'))
    drift = write_sources(root, outputs, check=args.check)
    print(json.dumps(dict(scope='F-03d1c limited player data', check=args.check, drift=drift), indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__ == '__main__': main()
