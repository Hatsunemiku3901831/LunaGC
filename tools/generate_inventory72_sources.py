"""Generate the reviewed inventory root; shared legacy item schemas remain separate."""
import argparse
import json
from pathlib import Path
import re

try:
    from .extract_client72 import HASHES, read_verified
    from .generate_born72_sources import OPCODES, PROTO, write_sources
    from .validate_protocol72 import validate
    from .client72_inventory_mapping import validate_inventory
except ImportError:
    from extract_client72 import HASHES, read_verified
    from generate_born72_sources import OPCODES, PROTO, write_sources
    from validate_protocol72 import validate
    from client72_inventory_mapping import validate_inventory


def render_sources(document, profile, raw, material, equip, opcode_source):
    errors = validate(document, profile) + validate_inventory(document, profile, raw, material, equip)
    if errors: raise ValueError('\n'.join(errors))
    for name, value in re.findall(r'public static final int (\w+) = (-?\d+);', opcode_source):
        if name != 'PlayerStoreNotify' and int(value) == 20892:
            raise ValueError('Unreviewed inventory command collision: ' + name)
    opcode_source, count = re.subn(r'public static final int PlayerStoreNotify = -?\d+;',
                                   'public static final int PlayerStoreNotify = 20892;', opcode_source)
    if count != 1: raise ValueError('Expected one canonical PlayerStoreNotify declaration')
    return {OPCODES: opcode_source, PROTO / 'PlayerStoreNotify.proto': (
        '// Generated by tools/generate_inventory72_sources.py from reviewed CN72 native contracts.\n'
        '// Unknown tag8 stays raw and is not sent as weight_limit. Nested adapter retains all raw fields.\n'
        'syntax = "proto3";\n\noption java_package = "emu.grasscutter.net.proto";\n'
        'option java_outer_classname = "PlayerStoreNotifyOuterClass";\n\n'
        'import "Client72InventoryWire.proto";\n\nmessage PlayerStoreNotify {\n'
        '  repeated cn72.inventorywire.NDGHFPMJFIM item_list = 2;\n'
        '  optional uint32 PAKLDABINMP = 8;\n  uint32 store_type = 14;\n}\n')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); root = Path(__file__).resolve().parents[1]
    for name, digest in HASHES.items(): read_verified(args.client / name, digest)
    directory = root / 'protocol/cn-7.2'
    values = [json.loads((directory / name).read_text('utf8')) for name in (
        'mappings.json', 'profile.json', 'inventory-graph-observations.json',
        'inventory-contract-observations.json', 'equip-contract-observations.json')]
    drift = write_sources(root, render_sources(*values, (root / OPCODES).read_text('utf8')), check=args.check)
    print(json.dumps(dict(scope='F-03d2c2 limited inventory root', check=args.check, drift=drift), indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__ == '__main__': main()
