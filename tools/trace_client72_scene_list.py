def validate_fixtures(rows):
    if len(rows) != len(DIRECT + SCENE) or {r['name'] for r in rows} != set(DIRECT + SCENE): raise ValueError('Incomplete scene list coverage')
    errors = {'nz-null-dictionary': NULL, 'nz-null-entry': NULL, 'nz-null-entries': NULL, 'nz-bounds-entry': BOUNDS,
              'ctor-null-target': NULL, 'ctor-null-source': ARGUMENT, 'nz-null-source': ARGUMENT, 'nz-ifix': IFIX,
              'ctor-noncollection': FALLBACK, 'nz-noncollection': FALLBACK}
    for row in rows:
        name = row['name']; expected_stop = errors.get(name, ZERO_RETURN if name.startswith('scene-zero') else NONZERO_RETURN if name.startswith('scene-') else RETURN)
        if row['stop'] != hex(expected_stop) or row['trace']['stop'] != hex(expected_stop): raise ValueError('List native boundary mismatch')
        addresses = row['trace']['executedAddresses']
        constructor = name.startswith('ctor-') or name.startswith('scene-zero')
        if hex(CONSTRUCTOR if constructor else NONZERO) not in addresses: raise ValueError('List consumer body omitted')
        if name in ERROR_SITES and hex(ERROR_SITES[name]) not in addresses: raise ValueError('Wrong original list error/IFix/fallback branch')
        if {hex(a) for a in (CONSTRUCTOR, NONZERO, INSERT_RANGE, TYPE_CHECK)} & set(row['trace']['models']): raise ValueError('List body/type helper replaced with model')
        expected = EXPECTED_ITEMS[name]
        if row['expectedItems'] != expected or not row['sourceUnchanged'] or row['reader']['storedObject']['repeatedUint32'] != expected:
            raise ValueError('Independent list input catalog/reader wire mismatch')
        if row['reader']['storedObject']['rawStoredScalars']['0x68'] != 0xFEDCBA9876543210: raise ValueError('Reader uint64 truncated')
        if name in errors:
            if name == 'nz-null-source' and (row['listAfter']['size'] != 0 or row['listAfter']['version'] != 10 or row['oldArrayAfter'] != row['listBefore']['rawArray'] or
                                             row['listAfter']['pointer'] != row['listBefore']['pointer'] or row['listAfter']['arrayPointer'] != row['listBefore']['arrayPointer']):
                raise ValueError('Null source lost original partial clear behavior')
            if name == 'nz-null-entry' and row['listAfter'] != row['listBefore']: raise ValueError('Null cached entry mutated old object')
            continue
        after, before = row['listAfter'], row['listBefore']
        if after['items'] != expected or after['size'] != len(expected) or after['rawArray'][:len(expected)] != expected or len(after['rawArray']) != after['capacity']:
            raise ValueError('Native list raw array/contents/size mismatch')
        if hex(TYPE_CHECK) not in addresses: raise ValueError('Native assignability helper omitted')
        version = 0 if constructor else 11 if before else 2
        if after['version'] != version: raise ValueError('Native list version/clear mismatch')
        if expected and after['arrayPointer'] == row['sourceArrayPointer']: raise ValueError('List shares source backing array')
        stores = row['nativeListWrites']
        if constructor:
            if expected and not any(w == dict(offset='0x18', size=4, value=len(expected), source='0x15881e3c6') for w in stores):
                raise ValueError('Native constructor size store omitted')
        elif not (any(w == dict(offset='0x18', size=4, value=0, source='0x153a3cc57') for w in stores) and
                  any(w == dict(offset='0x1c', size=4, value=version, source='0x15881fd1e') for w in stores)):
            raise ValueError('Native clear/final version stores omitted')
        events = [dict(kind='ICollection.Count', count=len(expected))]
        if expected: events.append(dict(kind='ICollection.CopyTo', count=len(expected), destinationIndex=0))
        if row['interfaceCalls'] != events: raise ValueError('ICollection fast path calls mismatch')
        if not constructor:
            if hex(INSERT_RANGE) not in addresses or len(row['dictionary']) != 1 or row['dictionary'][0]['key'] != row['key'] or row['dictionary'][0]['value'] != after['pointer']:
                raise ValueError('Native cached list/InsertRange mismatch')
            if before and after['pointer'] != before['pointer']: raise ValueError('Existing list identity changed')
            if before and before['capacity'] >= len(expected) and after['arrayPointer'] != before['arrayPointer']: raise ValueError('Reusable backing array replaced')
            if before and before['capacity'] >= len(expected) and after['rawArray'] != row['oldArrayAfter']: raise ValueError('Reused raw backing array differs from observed old storage')
            if before and before['capacity'] < len(expected) and (after['arrayPointer'] == before['arrayPointer'] or row['oldArrayAfter'] != before['rawArray']):
                raise ValueError('Native list growth/old array mismatch')
            if before and not expected and row['oldArrayAfter'] != before['rawArray']: raise ValueError('uint32 Clear incorrectly zeroed backing array')
        if name.startswith('scene-'):
            if hex(normal.ENTRY) not in addresses or hex(query.QUERY) not in addresses or not row['normalPrefix']['messageContentUnchanged']:
                raise ValueError('Same-reader normal/query path lost')
            raw = row['reader']['storedObject']['rawStoredScalars']['0x7c']
            if (((raw ^ 0x2D03) + 0xC0E3) & 0xFFFFFFFF) != row['key']: raise ValueError('Scene decoded key mismatch')


def recover(b, m, s, records, libraries):
    declared = declarations(b, m, s, records); e = Offline72(b, libraries, records, True); reader = SceneReader72(e)
    e.uc.mem_map(RETURN, 4096); e.uc.mem_write(RETURN, b'\xc3'); e.uc.mem_map(query.IFIX_TABLE, 0x400000)
    try:
        rows = [direct_fixture(reader, n) for n in DIRECT] + [scene_fixture(reader, n) for n in SCENE]
        code = {}
        for a in (NONZERO, CONSTRUCTOR, INSERT_RANGE, TYPE_CHECK, 0x1578B66F0, 0x1578B6A20):
            end = e.ends[a] if a == NONZERO else e.unwind_ranges[a]
            raw = b[e.pe.offset(a, end - a, executable=True):][:end - a]
            code[hex(a)] = dict(size=len(raw), sha256=hashlib.sha256(raw).hexdigest())
    finally:
        reader.close(); e.close()
    validate_fixtures(rows)
    return dict(schemaVersion=1, inputSHA256=HASHES, declarations=declared, nativeCode=code, fixtures=rows, fixtureCount=len(rows),
                runtimeStatus='not-tested', targetProtocolReady=False, fallbackBodyExecuted=False,
                models=['normal/query explicit storage reused without changing existing files',
                        'initialized synthetic ICollection metadata; actual native assignability/interface dispatch executes',
                        'ICollection.Count reads the actual reader object count; CopyTo copies its raw uint32 array with declared bounds',
                        'managed uint32 arrays/allocation/copy from SceneReader72; fixed cache dictionary and generic binder storage'],
                outsideScope=['IEnumerable fallback158820740 body', 'actual runtime closed generic ABI/IFix implementations',
                              'unknown scene business meanings', 'scene code after consumer returns', 'SDK/media/network order/live scene entry/D-02'])


