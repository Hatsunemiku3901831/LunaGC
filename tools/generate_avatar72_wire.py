def canonical_sha256(value):
    return hashlib.sha256((json.dumps(value, indent=2) + '\n').encode('utf8')).hexdigest()


def render_sources(raw, sources):
    if canonical_sha256(raw) != RAW_CANONICAL_SHA256 or raw.get('inputSHA256') != HASHES:
        raise ValueError('Approved complete Avatar raw evidence changed')
    if set(sources) != set(SOURCE_CANONICAL_SHA256) or any(canonical_sha256(sources[name]) != digest for name, digest in SOURCE_CANONICAL_SHA256.items()):
        raise ValueError('Approved Avatar dependency evidence changed')
    names = {row['typeIndex']: row['clientType'] for row in raw['closureMessages']}; messages = []
    for row in sorted(raw['closureMessages'], key=lambda item: item['typeIndex']):
        lines, groups = [], {}
        for field in sorted(row['fields'], key=lambda item: item['tag']):
            kind = names[field['nestedTypeIndex']] if field['type'] == 'message' else field['type']
            if kind == 'map':
                value = names[field['nestedTypeIndex']] if field['valueType'] == 'message' else field['valueType']
                kind = f"map<{field['keyType']}, {value}>"
            group = field.get('oneof') or ('raw_object_' + format(field['objectOffset'], 'x') if 'discriminatorOffset' in field else None)
            prefix = 'repeated ' if field['cardinality'] == 'repeated' else 'optional ' if field['type'] not in ('message', 'map') and not group else ''
            packing = ' [packed = true]' if field.get('packed') else ''
            line = f"  {prefix}{kind} {field['clientField']} = {field['tag']}{packing};"
            if group: groups.setdefault(group, []).append(line)
            else: lines.append(line)
        for name, branches in groups.items(): lines += ['  oneof ' + name + ' {'] + ['  ' + line for line in branches] + ['  }']
        messages.append('message ' + row['clientType'] + ' {\n' + '\n'.join(lines) + '\n}\n')
    return {OUTPUT: (
        '// Generated by tools/generate_avatar72_wire.py from fixed complete native raw evidence.\n'
        '// Raw names only; no legacy schema, sender, opcode or business-meaning migration.\n'
        '// Optional ordinary scalars preserve explicit-zero merge; not recovered original Proto syntax.\n'
        'syntax = "proto3";\n\npackage cn72.avatarwire;\n'
        'option java_package = "emu.grasscutter.net.proto";\n'
        'option java_outer_classname = "Client72AvatarWireOuterClass";\n\n' + '\n'.join(messages))}


def load_evidence(directory):
    raw = json.loads((directory / 'avatar-complete-raw-observations.json').read_text('utf8'))
    sources = {name: json.loads((directory / ('avatar-' + name + '-observations.json')).read_text('utf8')) for name in SOURCE_CANONICAL_SHA256}
    return raw, sources


def native_cases(raw, sources):
    """Only independently executed complete objects; retain source/name identity."""
    types = {row['typeIndex'] for row in raw['closureMessages']}; cases = []
    for source, report in [('complete-raw', raw), *sources.items()]:
        for row in report['fixtures']:
            if row['typeIndex'] not in types or 'untracedType' in json.dumps(row['result']): continue
            if row['name'] == 'signed-negative-packed-length-no-append': continue
            cases.append(dict(source=source, name=row['name'], typeIndex=row['typeIndex'], wire=row['wire'], expected=row['result']))
    return cases


def main():
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--client', type=Path, required=True); parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); root = Path(__file__).resolve().parents[1]
    for name, digest in HASHES.items(): read_verified(args.client / name, digest)
    raw, sources = load_evidence(root / 'protocol/cn-7.2'); drift = write_sources(root, render_sources(raw, sources), check=args.check)
