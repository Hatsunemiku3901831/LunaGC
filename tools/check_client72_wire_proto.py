"""Compile research Proto and assert independently written target-derived wire.

Requires an explicit protoc path. No database/server/client execution. Expected
bytes below were written from native tags and writer semantics, not generated by
the same schema. They are synthetic non-sensitive values, not captured traffic.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
PROTO = ROOT / 'protocol/cn-7.2/research.proto'
HEADER_TEXT = b'''MIBNHKIPDIM: 4660 BCNJAEDGBCK: 4294967297 POAOKGCEJPF: 127
KNKMLHHGPPE: 128 BNHLJEGKGEM: 300 FKKOHHCLCPH: 4294967295'''
HEADER_WIRE = bytes.fromhex('18b424 308180808010 387f 408001 48ac02 50ffffffff0f')
PING_TEXT = br'''LBEAJJBNBIF: 4294967297 BFNKMJBHCKJ: 60 IMEDCDCPICN: "\000\377"
MHCBMOHFBCK: 1.5 BAHKGFLONLL: "AB" HDLNEABIBJF: 2.5 OILKPHNHCHB: 1700000000 AMLHAGPHMHN: 300'''
PING_WIRE = bytes.fromhex('088180808010 103c 1a0200ff 29000000000000f83f 4a024142 5500002040 6880e2cfaa06 70ac02')


class WireAssertions(unittest.TestCase):
    protoc = None

    @classmethod
    def setUpClass(cls):
        if cls.protoc is None:
            raise RuntimeError('Run this script with --protoc; tests must not silently skip')
        with tempfile.TemporaryDirectory() as directory:
            result = subprocess.run([str(cls.protoc), '--proto_path=' + str(PROTO.parent),
                                     '--descriptor_set_out=' + str(Path(directory) / 'p0.pb'), str(PROTO)],
                                    capture_output=True)
            if result.returncode:
                raise RuntimeError(result.stderr.decode('utf8', errors='replace'))

    def run_protoc(self, name, data, mode='encode', success=True):
        result = subprocess.run([str(self.protoc), '--proto_path=' + str(PROTO.parent),
                                 f'--{mode}=cn72.research.{name}', str(PROTO)], input=data, capture_output=True)
        self.assertEqual(success, result.returncode == 0, result.stderr.decode('utf8', errors='replace'))
        return result.stdout

    def test_header_all_nonzero_fields_and_64bit(self):
        self.assertEqual(HEADER_WIRE, self.run_protoc('LOPNMMJPFAJ', HEADER_TEXT))

    def test_ping_all_nonzero_bytes_floats_and_64bit(self):
        self.assertEqual(PING_WIRE, self.run_protoc('LMINJCCKNDD', PING_TEXT))

    def test_independent_header_wire_decode(self):
        decoded = self.run_protoc('LOPNMMJPFAJ', HEADER_WIRE, 'decode')
        for line in (b'MIBNHKIPDIM: 4660', b'BCNJAEDGBCK: 4294967297', b'FKKOHHCLCPH: 4294967295'):
            self.assertIn(line, decoded)

    def test_independent_ping_wire_decode(self):
        decoded = self.run_protoc('LMINJCCKNDD', PING_WIRE, 'decode')
        for line in (b'OILKPHNHCHB: 1700000000', b'HDLNEABIBJF: 2.5', b'MHCBMOHFBCK: 1.5'):
            self.assertIn(line, decoded)

    def test_unsigned_maximum_and_overflow(self):
        self.assertEqual(bytes.fromhex('08ffffffffffffffffff01'), self.run_protoc(
            'LMINJCCKNDD', b'LBEAJJBNBIF: 18446744073709551615'))
        for text in (b'LBEAJJBNBIF: 18446744073709551616', b'BFNKMJBHCKJ: 4294967296', b'BFNKMJBHCKJ: -1'):
            self.run_protoc('LMINJCCKNDD', text, success=False)

    def test_zero_defaults_empty_payload_and_repeated_singular_last_wins(self):
        self.assertEqual(b'', self.run_protoc('LMINJCCKNDD', b'LBEAJJBNBIF: 0 IMEDCDCPICN: ""'))
        decoded = self.run_protoc('LOPNMMJPFAJ', bytes.fromhex('18011802'), 'decode')
        self.assertEqual(b'MIBNHKIPDIM: 2', decoded.strip())

    def test_unknown_tag_is_not_aliased_to_known_field(self):
        decoded = self.run_protoc('LOPNMMJPFAJ', bytes.fromhex('1801800109'), 'decode')
        self.assertIn(b'MIBNHKIPDIM: 1', decoded)
        self.assertIn(b'16: 9', decoded)

    def test_float_negative_zero_is_omitted_nan_and_infinity_are_written(self):
        # Native ucomis{d,s} zero checks omit both signed zeroes, but retain NaN.
        self.assertEqual(b'', self.run_protoc('LMINJCCKNDD', b'HDLNEABIBJF: -0 MHCBMOHFBCK: -0'))
        self.assertEqual(bytes.fromhex('550000c07f'), self.run_protoc('LMINJCCKNDD', b'HDLNEABIBJF: nan'))
        self.assertEqual(bytes.fromhex('29000000000000f07f'), self.run_protoc('LMINJCCKNDD', b'MHCBMOHFBCK: inf'))

    def test_truncated_varint_bytes_fixed32_fixed64_rejected(self):
        for wire in ('0880', '1a02ff', '55000020', '29000000000000f8'):
            self.run_protoc('LMINJCCKNDD', bytes.fromhex(wire), 'decode', success=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--protoc', required=True, type=Path)
    args = parser.parse_args()
    WireAssertions.protoc = args.protoc.resolve(strict=True)
    print(subprocess.check_output([str(WireAssertions.protoc), '--version'], text=True).strip(), flush=True)
    result = unittest.TextTestRunner(verbosity=2).run(unittest.defaultTestLoader.loadTestsFromTestCase(WireAssertions))
    raise SystemExit(not result.wasSuccessful())


if __name__ == '__main__':
    main()
