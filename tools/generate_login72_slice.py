"""Generate the reviewed TokenReq/heartbeat/header wire slice, not a ready server.

Only previously verified business names survive. Other fields use the fixed
client's raw names, including heartbeat echo fields whose semantics are pending.
AstaPS a49f51a is a comparison source; it cannot override target observations.
"""
import argparse
import json
from pathlib import Path
import re

try:
    from .extract_client72 import HASHES, read_verified
    from .generate_born72_sources import OPCODES, PROTO, write_sources
    from .validate_protocol72 import validate
except ImportError:
    from extract_client72 import HASHES, read_verified
    from generate_born72_sources import OPCODES, PROTO, write_sources
    from validate_protocol72 import validate


NAMES = ('GetPlayerTokenReq', 'PingReq', 'PingRsp', 'PacketHead')
SEMANTICS = {
    'GetPlayerTokenReq': {2: 'account_token', 3: 'channel_id', 9: 'account_uid',
                          10: 'sub_channel_id', 11: 'is_guest', 15: 'account_type',
                          623: 'client_rand_key', 1184: 'key_id'},
    'PingReq': {}, 'PingRsp': {},
    'PacketHead': {3: 'client_sequence_id', 6: 'sent_ms'},
}
COMMANDS = {'GetPlayerTokenReq': 24604, 'PingReq': 26605, 'PingRsp': 25763}
# The only legacy collision has no production/test references. It is not a 7.2 alias.
RETIRED = {'LCNLHAOBBFE': (24604, -124604)}


def render_sources(document, profile, wire, token, opcode_source):
    errors = validate(document, profile)
    if any(report.get('inputSHA256') != HASHES for report in (wire, token)):
        errors.append('Observations differ from the fixed CN 7.2 target')
    observed = {r['clientType']: r for r in wire['messages']}
    observed[token['clientType']] = token
    tables = {key: {r['semanticName']: r for r in document[key]}
              for key in ('opcodes', 'messages', 'schemas')}
    outputs = {}
    for name in NAMES:
        opcode, message, schema = (tables[k][name] for k in tables)
        if any(row['status'] != 'verified' for row in (opcode, message)):
            errors.append(f'{name}: opcode and message identity must be verified')
        raw = observed.get(message.get('clientType'))
        if raw is None:
            errors.append(f'{name}: target wire observation missing')
            continue
        fields = sorted(schema['fields'], key=lambda f: f['tag'])
        key = lambda f: (f['clientField'], f['tag'], f['type'], f['cardinality'],
                         f['presence'], f['packed'])
        if [key(f) for f in fields] != [key(f) for f in sorted(raw['fields'], key=lambda f: f['tag'])]:
            errors.append(f'{name}: field table differs from independent target wire')
        if {f['tag']: f['semanticField'] for f in fields if f['status'] == 'verified'} != SEMANTICS[name]:
            errors.append(f'{name}: reviewed semantic boundary changed')
        lines = []
        for field in fields:
            if field['cardinality'] != 'singular' or field['type'] not in {
                    'string', 'bytes', 'bool', 'uint32', 'uint64', 'int32', 'float', 'double'}:
                errors.append(f'{name}: field outside reviewed scalar slice')
            identifier = SEMANTICS[name].get(field['tag'], field['clientField'])
            if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', identifier):
                errors.append(f'{name}: invalid field identifier')
            suffix = '' if field['tag'] in SEMANTICS[name] else ' // Raw target name; business meaning unverified.'
            lines.append(f"  {field['type']} {identifier} = {field['tag']};{suffix}")
        outputs[PROTO / f'{name}.proto'] = (
            '// Generated by tools/generate_login72_slice.py from fixed CN 7.2 evidence.\n'
            '// F-02a wire slice only; not P0 readiness or client acceptance.\n'
            'syntax = "proto3";\n\n'
            'option java_package = "emu.grasscutter.net.proto";\n'
            f'option java_outer_classname = "{name}OuterClass";\n\n'
            f'message {name} {{\n' + '\n'.join(lines) + '\n}\n')
        if name in COMMANDS and opcode.get('cmdId') != COMMANDS[name]:
            errors.append(f'{name}: reviewed CmdID changed')

    for name, (old, inactive) in RETIRED.items():
        match = re.search(rf'public static final int {name} = (-?\d+);', opcode_source)
        if match is None or int(match[1]) not in (old, inactive):
            errors.append(f'{name}: unexpected legacy collision state')
        opcode_source = re.sub(rf'public static final int {name} = -?\d+;',
                              f'public static final int {name} = {inactive};', opcode_source)
    for other, value in re.findall(r'public static final int (\w+) = (-?\d+);', opcode_source):
        if other not in COMMANDS and int(value) in COMMANDS.values():
            errors.append(f'{other}: collides with a reviewed 7.2 command')
    for name, value in COMMANDS.items():
        opcode_source, count = re.subn(rf'public static final int {name} = -?\d+;',
                                      f'public static final int {name} = {value};', opcode_source)
        if count != 1:
            errors.append(f'{name}: expected one canonical declaration')
    outputs[OPCODES] = opcode_source
    if errors:
        raise ValueError('\n'.join(errors))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--client', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for path, digest in HASHES.items():
        read_verified(args.client / path, digest)
    directory = root / 'protocol/cn-7.2'
    inputs = [json.loads((directory / name).read_text('utf8')) for name in (
        'mappings.json', 'profile.json', 'wire-observations.json', 'token-wire-observations.json')]
    outputs = render_sources(*inputs, (root / OPCODES).read_text('utf8'))
    drift = write_sources(root, outputs, check=args.check)
    print(json.dumps(dict(scope='F-02a wire slice only', check=args.check, drift=drift), indent=2))
    raise SystemExit(bool(drift) if args.check else 0)


if __name__ == '__main__':
    main()
