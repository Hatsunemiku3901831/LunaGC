import argparse
import json
from pathlib import Path
import subprocess
try:
    from .observed_proto72 import compare_fixtures
    from .extract_client72 import HASHES
except ImportError:
    from observed_proto72 import compare_fixtures
    from extract_client72 import HASHES


def main():
    p = argparse.ArgumentParser(description='Compare LoginReq nested/oneof native fixtures with protoc')
    p.add_argument('--protoc', required=True, type=Path); p.add_argument('--trace', required=True, type=Path)
    p.add_argument('--directory', type=Path, default=Path(__file__).resolve().parents[1] / 'protocol/cn-7.2'); a = p.parse_args()
    mapping = json.loads((a.directory/'login-wire-observations.json').read_text('utf8'))
    trace = json.loads(a.trace.read_text('utf8'))
    if mapping['inputSHA256'] != HASHES or trace['inputSHA256'] != HASHES: raise ValueError('Wrong target')
    proto = (a.directory/'login-research.proto').resolve()
    n = compare_fixtures(a.protoc.resolve(), proto, mapping, trace)
    # Independent oracles from native key stores/cctor codec, not generated by these schemas.
    oracles = [('PBBDOCEDNIE', 'CJMJBINEBAG: -1 ALOKJBKPLGA: 300', '08ffffffffffffffffff0110ac02'),
               ('NBFMIBMFJIO', 'FPLGHNBLIAJ: 1 FPLGHNBLIAJ: 128 NFEFAIFMOCD: true', '0a030180012801'),
               ('KEDIEGLJIMC', 'case_13 { JMHKHAPJADA: 1 DOHJIJIJDEO: 2 }', '6a0408011002')]
    for name, text, expected in oracles:
        r = subprocess.run([str(a.protoc.resolve()), '--proto_path='+str(proto.parent), '--encode=cn72.research.'+name, str(proto)], input=text.encode(), capture_output=True, check=True)
        if r.stdout.hex()!=expected: raise ValueError('Independent wire oracle failed for '+name)
    print(json.dumps(dict(nativeComparisons=n, independentWireAssertions=len(oracles), runtimeStatus='not-tested')))


if __name__=='__main__': main()
